// Use DPT_UPMS2's original theme/maps and the complete PHP reference lists.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const php = resolve(project, '..', 'DPT_UPMS2');
const reference = resolve(project, '..');
const assets = [
  ['bower_components/bootstrap/dist/css/bootstrap.css', 'bootstrap/css/bootstrap.css'],
  ['bower_components/font-awesome/css/font-awesome.css', 'font-awesome/css/font-awesome.css'],
  ['dist/style.css', 'dist/style.css'],
  ['dist/skin-green-light.css', 'dist/skin-green-light.css'],
  ['img/map/main.jpg', 'img/map/main.jpg'],
  ...[1, 2, 3, 4, 5].map(id => [`img/map/${id}.jpg`, `img/map/${id}.jpg`]),
  ['img/keth/main.png', 'img/keth/main.png'],
  ...Array.from({ length: 18 }, (_, index) => [`img/keth/${index + 1}.png`, `img/keth/${index + 1}.png`]),
  ['ChartJs/ChartJs.js', 'ChartJs/ChartJs.js'],
  ['pdf/UPMS_SuperAdmin_Manual.pdf', 'pdf/UPMS_SuperAdmin_Manual.pdf'],
  ...['eot', 'svg', 'ttf', 'woff', 'woff2'].map(ext => [
    `bower_components/font-awesome/fonts/fontawesome-webfont.${ext}`,
    `font-awesome/fonts/fontawesome-webfont.${ext}`,
  ]),
  ...['eot', 'svg', 'ttf', 'woff', 'woff2'].map(ext => [
    `bower_components/bootstrap/dist/fonts/glyphicons-halflings-regular.${ext}`,
    `bootstrap/fonts/glyphicons-halflings-regular.${ext}`,
  ]),
];
for (const [source, destination] of assets) {
  const target = resolve(project, 'client/public/php', destination);
  mkdirSync(dirname(target), { recursive: true });
  copyFileSync(resolve(php, source), target);
}

const regionalSource = readFileSync(resolve(reference, 'app/show_extra.php'), 'utf8');
const regionalList = regionalSource.split('$static_park_provinces = [')[1].split('?>')[0];
const names = ['ภาคเหนือ', 'ภาคตะวันออกเฉียงเหนือ', 'ภาคกลาง', 'ภาคตะวันออก', 'ภาคใต้'];
const colors = ['#979728', '#9b487a', '#3e6633', '#33a1ab', '#316aa5'];
const links = [...regionalSource.split('$drive_links = [')[1].split('];')[0].matchAll(/'(https:[^']+)'/g)].map(m => m[1]);
const sqlReference = readFileSync(resolve(reference, 'dpt_cityplan.sql'), 'utf8').split('INSERT INTO `ref_province`')[1].split(';')[0];
const sqlProvinces = [...sqlReference.matchAll(/\((\d+), '([^']+)', (\d+), (\d+), (\d+), '[^']*'\)/g)].map(p => ({ id: Number(p[1]), name: p[2], affiliationId: Number(p[3]), regionId: Number(p[4]), kethId: Number(p[5]) }));
if (sqlProvinces.length !== 77) throw new Error('Review the SQL province reference before synchronizing.');
const kethGroups = Array.from({ length: 18 }, (_, i) => {
  const provinces = sqlProvinces.filter(p => p.kethId === i + 1);
  return { id: i + 1, regionId: provinces[0].regionId, provinces };
});
const regions = [...regionalList.matchAll(/\n\s*(\d+) => \[([\s\S]*?)\n\s*\]/g)].map(match => {
  const id = Number(match[1]);
  const provinces = sqlProvinces.filter(p => p.regionId === id);
  return { id, name: names[id - 1], color: colors[id - 1], driveUrl: links[id - 1], provinces };
});
const provinces = regions.flatMap(r => r.provinces);
if (regions.length !== 5 || kethGroups.length !== 18 || provinces.length !== 77 ||
    new Set(provinces.map(p => p.id)).size !== 77 || provinces.some(p => p.kethId === undefined)) {
  throw new Error('PHP geography changed: review the parser before synchronizing.');
}
const header = '// Generated by scripts/sync-php-reference.mjs from the PHP source.\n';
const keths = kethGroups.map(k => ({
  ...k, name: `เขตตรวจราชการที่ ${k.id}`, color: colors[k.regionId - 1],
}));
const clientData = `${header}import type { RegionInfo, KethInfo } from '../types/plan';\n\n` +
  `export const PHP_REGIONS: (RegionInfo & { driveUrl: string })[] = ${JSON.stringify(regions.map(r => ({ ...r, planCount: 0 })), null, 2)};\n\n` +
  `export const PHP_KETHS: KethInfo[] = ${JSON.stringify(keths.map(k => ({ kethId: k.id, name: k.name, color: k.color, regionName: names[k.regionId - 1], provinces: k.provinces, planCount: 0 })), null, 2)};\n`;
mkdirSync(resolve(project, 'client/src/data'), { recursive: true });
writeFileSync(resolve(project, 'client/src/data/phpReference.ts'), clientData);
writeFileSync(resolve(project, 'server/src/data/provinces.ts'), `${header}import type { ProvinceInfo } from '../types/plan';\n\nexport const PROVINCES: ProvinceInfo[] = ${JSON.stringify(provinces, null, 2)};\n`);
console.log('Synchronized DPT_UPMS2 styles, fonts and maps; PHP reference lists: 77 provinces, 5 regions and 18 inspectorates.');
await import('./sync-tree-report.mjs');
